#!/usr/bin/env node
/**
 * Dependabot stuck-CI watch.
 *
 * Lists open Dependabot PRs that have been open for more than STUCK_DAYS
 * (default 7) with failing or missing CI checks. Exits with code 1 if any
 * stuck PRs are found so the calling workflow can create a notification issue.
 *
 * Requires: GITHUB_TOKEN (provided automatically in Actions), gh CLI.
 * Optional env: STUCK_DAYS (default 7), REPO (default: detected from git remote).
 */

import { execSync } from 'node:child_process';

const STUCK_DAYS = Number(process.env.STUCK_DAYS ?? 7);
const NOW = Date.now();
const MS_PER_DAY = 86_400_000;

/** @param {string} cmd */
const run = (cmd) => execSync(cmd, { encoding: 'utf8' }).trim();

/** @param {string} cmd @returns {unknown} */
const runJson = (cmd) => JSON.parse(run(cmd));

/**
 * @typedef {{ number: number; title: string; createdAt: string; headRefOid: string }} PrSummary
 * @typedef {{ name: string; conclusion: string | null; status: string }} CheckRun
 */

const prs = /** @type {PrSummary[]} */ (
  runJson(`gh pr list --author "app/dependabot" --state open --json number,title,createdAt,headRefOid --limit 50`)
);

if (prs.length === 0) {
  console.log('[watch] No open Dependabot PRs found.');
  process.exit(0);
}

console.log(`[watch] Found ${prs.length} open Dependabot PR(s). Checking for stuck CIs…`);

/** @type {{ pr: PrSummary; agedays: number; checkSummary: string }[]} */
const stuck = [];

for (const pr of prs) {
  const ageDays = (NOW - new Date(pr.createdAt).getTime()) / MS_PER_DAY;

  if (ageDays < STUCK_DAYS) {
    console.log(`  PR #${pr.number} — ${ageDays.toFixed(1)}d old, not yet stuck.`);
    continue;
  }

  // Fetch check runs for the latest commit on this PR's head.
  let checkSummary = 'no checks';
  try {
    const checksPayload = /** @type {{ checkRuns: CheckRun[] }} */ (
      runJson(`gh api /repos/{owner}/{repo}/commits/${pr.headRefOid}/check-runs --jq '{checkRuns:[.check_runs[]|{name:.name,status:.status,conclusion:.conclusion}]}'`)
    );
    const checks = checksPayload.checkRuns ?? [];
    if (checks.length === 0) {
      checkSummary = 'no checks';
    } else {
      const failing = checks.filter((c) => c.conclusion === 'failure' || c.conclusion === 'timed_out');
      const pending = checks.filter((c) => c.status === 'in_progress' || c.status === 'queued');
      if (failing.length > 0) checkSummary = `${failing.length} failing check(s)`;
      else if (pending.length > 0) checkSummary = `${pending.length} pending check(s)`;
      else checkSummary = 'all checks passed';
    }
  } catch (err) {
    checkSummary = `check fetch error: ${err instanceof Error ? err.message : String(err)}`;
  }

  // Flag as stuck if checks are not all passing (or if there are no checks after STUCK_DAYS).
  const isStuck = checkSummary !== 'all checks passed';
  console.log(`  PR #${pr.number} — ${ageDays.toFixed(1)}d old, ${checkSummary}${isStuck ? ' → STUCK' : ''}`);

  if (isStuck) {
    stuck.push({ pr, agedays: ageDays, checkSummary });
  }
}

if (stuck.length === 0) {
  console.log('[watch] No stuck Dependabot PRs. All clear.');
  process.exit(0);
}

// Output a markdown report to STUCK_REPORT env file so the workflow can use it.
const reportLines = [
  `## Stuck Dependabot PRs (${stuck.length})`,
  '',
  '| PR | Age | Status |',
  '|---|---|---|',
  ...stuck.map(({ pr, agedays, checkSummary }) =>
    `| #${pr.number} [${pr.title}](../../pull/${pr.number}) | ${agedays.toFixed(1)}d | ${checkSummary} |`
  ),
  '',
  '_Generated by dependabot-stuck-ci-watch. Review and resolve or close these PRs._'
];
const report = reportLines.join('\n');

console.log('\n[watch] Stuck PR report:\n');
console.log(report);

// Write report to GITHUB_OUTPUT if available (for use in the workflow).
const outputFile = process.env.GITHUB_OUTPUT;
if (outputFile) {
  const { appendFileSync } = await import('node:fs');
  appendFileSync(outputFile, `stuck_count=${stuck.length}\n`);
  appendFileSync(outputFile, `stuck_report<<STUCK_REPORT_EOF\n${report}\nSTUCK_REPORT_EOF\n`);
}

process.exit(1); // signal to caller that stuck PRs exist
